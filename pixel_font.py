def _glyph_cells(ch):
    rows = _RAW.get(ch.upper(), _RAW[" "])
    return {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"}


def text_cell_width(text, spacing=1):
    return len(text) * (GLYPH_W + spacing) - spacing


def render_pixel_text(text, scale=6, fill=(255, 255, 255), outline=(0, 0, 0), shadow=(0, 0, 0, 120), spacing=1):
    """Draw `text` in the pixel font.

    fill    : one RGB colour, or a list of 7 colours (one per pixel row) for a gradient look.
    outline : RGB colour of the 1-cell border (None to skip).
    shadow  : RGBA colour of a 1-cell drop shadow (None to skip).
    """
    fill_cells = set()
    for i, ch in enumerate(text):
        ox = i * (GLYPH_W + spacing)
        for (x, y) in _glyph_cells(ch):
            fill_cells.add((ox + x, y))

    outline_cells = set()
    if outline is not None:
        for (x, y) in fill_cells:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    n = (x + dx, y + dy)
                    if n not in fill_cells:
                        outline_cells.add(n)

    shadow_cells = set()
    if shadow is not None:
        for (x, y) in fill_cells | outline_cells:
            n = (x + 1, y + 1)
            if n not in fill_cells and n not in outline_cells:
                shadow_cells.add(n)

    pad = 3
    cells_w = text_cell_width(text, spacing) + pad * 2
    cells_h = GLYPH_H + pad * 2
    img = Image.new("RGBA", (cells_w * scale, cells_h * scale), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    def paint(cells, color_for):
        for (x, y) in cells:
            px = (x + pad) * scale
            py = (y + pad) * scale
            draw.rectangle([px, py, px + scale - 1, py + scale - 1], fill=color_for(y))

    if shadow is not None:
        paint(shadow_cells, lambda y: tuple(shadow) if len(shadow) == 4 else tuple(shadow) + (255,))
    if outline is not None:
        paint(outline_cells, lambda y: tuple(outline) + (255,))

    def fill_color(y):
        if isinstance(fill, list):
            row = min(max(y, 0), GLYPH_H - 1)
            return tuple(fill[row]) + (255,)
        return tuple(fill) + (255,)

    paint(fill_cells, fill_color)
    return img
